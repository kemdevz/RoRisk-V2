create table if not exists public.rorisk_battles (
  uuid uuid primary key default gen_random_uuid(),
  battle_id bigint generated by default as identity unique,
  creator_uuid uuid not null references public.rorisk_users(uuid) on delete restrict,
  currency text not null check (currency in ('coins', 'rocoins')),
  mode text not null default 'standard' check (mode in ('standard', 'group', '2v2', '3v3', '2v2v2')),
  player_count smallint not null check (player_count between 2 and 6),
  state text not null default 'created' check (state in ('created', 'countdown', 'pending', 'rolling', 'jackpot_spinning', 'completed', 'cancelled')),
  amount bigint not null check (amount >= 0),
  join_amount bigint not null check (join_amount >= 0),
  creator_cost bigint not null check (creator_cost >= 0),
  total_rounds smallint not null check (total_rounds between 1 and 50),
  current_round smallint not null default 0 check (current_round between 0 and 50),
  cases jsonb not null default '[]'::jsonb check (jsonb_typeof(cases) = 'array'),
  players jsonb not null default '[]'::jsonb check (jsonb_typeof(players) = 'array'),
  results jsonb not null default '[]'::jsonb check (jsonb_typeof(results) = 'array'),
  options jsonb not null default '{}'::jsonb check (jsonb_typeof(options) = 'object'),
  server_seed_hash text not null,
  server_seed text not null,
  client_seed text not null,
  nonce bigint not null default 0 check (nonce >= 0),
  eos_block_number bigint,
  eos_block_id text,
  winner_slots smallint[] not null default '{}',
  payout_amount bigint not null default 0 check (payout_amount >= 0),
  version bigint not null default 1,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  updated_at timestamptz not null default now()
);

alter table public.rorisk_battles add column if not exists cases jsonb not null default '[]'::jsonb;
alter table public.rorisk_battles add column if not exists players jsonb not null default '[]'::jsonb;
alter table public.rorisk_battles add column if not exists results jsonb not null default '[]'::jsonb;

