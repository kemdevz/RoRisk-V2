create or replace function public.create_rorisk_battle(
  p_user_uuid uuid, p_currency text, p_mode text, p_player_count integer,
  p_amount bigint, p_join_amount bigint, p_creator_cost bigint, p_options jsonb,
  p_cases jsonb, p_client_seed text, p_server_seed text, p_server_seed_hash text
) returns jsonb
language plpgsql security definer set search_path = public, extensions
as $$
declare
  v_user public.rorisk_users%rowtype;
  v_battle public.rorisk_battles%rowtype;
  v_balance bigint;
  v_creator jsonb;
begin
  if p_currency not in ('coins', 'rocoins') then raise exception 'The selected currency is invalid.'; end if;
  if p_mode not in ('standard', 'group', '2v2', '3v3', '2v2v2') then raise exception 'The selected battle mode is invalid.'; end if;
  if p_player_count not between 2 and 6 then raise exception 'The selected player count is invalid.'; end if;
  if jsonb_typeof(p_cases) <> 'array' or jsonb_array_length(p_cases) not between 1 and 50 then raise exception 'Select between 1 and 50 cases.'; end if;
  if p_amount < 0 or p_join_amount < 0 or p_creator_cost < 0 then raise exception 'The battle cost is invalid.'; end if;
  if encode(digest(p_server_seed, 'sha256'), 'hex') <> p_server_seed_hash then raise exception 'The battle seed is invalid.'; end if;
  select * into v_user from public.rorisk_users where uuid = p_user_uuid for update;
  if not found then raise exception 'Please sign in to perform this action.'; end if;
  v_balance := case when p_currency = 'coins' then coalesce(v_user.coins, 0) else coalesce(v_user.rocoins, 0) end;
  if v_balance < p_creator_cost then raise exception 'Insufficient balance.'; end if;
  if p_currency = 'coins' then
    update public.rorisk_users set coins = coins - p_creator_cost where uuid = p_user_uuid returning * into v_user;
  else
    update public.rorisk_users set rocoins = rocoins - p_creator_cost where uuid = p_user_uuid returning * into v_user;
  end if;
  v_creator := jsonb_build_object(
    'uuid', gen_random_uuid(), 'slot', 0, 'team', 0, 'user_uuid', v_user.uuid,
    'roblox_id', v_user.roblox_id, 'username', v_user.username,
    'avatar_headshot', coalesce(v_user.avatar_headshot, '/default-avatar.png'),
    'rank', coalesce(v_user.rank, 'user'), 'level', coalesce(v_user.level, 0),
    'is_bot', false, 'wager_amount', p_creator_cost, 'outcome_total', 0,
    'payout_amount', 0, 'joined_at', now()
  );
  insert into public.rorisk_battles (
    creator_uuid, currency, mode, player_count, amount, join_amount, creator_cost,
    total_rounds, cases, players, options, client_seed, server_seed, server_seed_hash
  ) values (
    p_user_uuid, p_currency, p_mode, p_player_count, p_amount, p_join_amount, p_creator_cost,
    jsonb_array_length(p_cases), p_cases, jsonb_build_array(v_creator), coalesce(p_options, '{}'::jsonb),
    left(coalesce(p_client_seed, p_user_uuid::text), 128), p_server_seed, p_server_seed_hash
  ) returning * into v_battle;
  return jsonb_build_object('battle', to_jsonb(v_battle), 'user', to_jsonb(v_user));
end;
$$;

create or replace function public.join_rorisk_battle(p_battle_uuid uuid, p_user_uuid uuid, p_slot integer)
returns jsonb language plpgsql security definer set search_path = public, extensions
as $$
declare
  v_user public.rorisk_users%rowtype;
  v_battle public.rorisk_battles%rowtype;
  v_balance bigint;
  v_team integer;
  v_player jsonb;
  v_count integer;
begin
  select * into v_battle from public.rorisk_battles where uuid = p_battle_uuid for update;
  if not found then raise exception 'This battle could not be found.'; end if;
  if v_battle.state <> 'created' then raise exception 'This battle can no longer be joined.'; end if;
  if p_slot < 0 or p_slot >= v_battle.player_count then raise exception 'That battle seat is invalid.'; end if;
  if exists (select 1 from jsonb_array_elements(v_battle.players) player where (player->>'slot')::integer = p_slot) then raise exception 'That battle seat is already occupied.'; end if;
  if exists (select 1 from jsonb_array_elements(v_battle.players) player where player->>'user_uuid' = p_user_uuid::text) then raise exception 'You have already joined this battle.'; end if;
  select * into v_user from public.rorisk_users where uuid = p_user_uuid for update;
  if not found then raise exception 'Please sign in to perform this action.'; end if;
  if coalesce(v_battle.options->>'affiliateOnly', 'false')::boolean and coalesce(v_user.rank, 'user') = 'user' then raise exception 'This battle is only available to eligible affiliates.'; end if;
  if coalesce((v_battle.options->>'levelMin')::integer, 0) > coalesce(v_user.level, 0) then raise exception 'Your level is too low to join this battle.'; end if;
  v_balance := case when v_battle.currency = 'coins' then coalesce(v_user.coins, 0) else coalesce(v_user.rocoins, 0) end;
  if v_balance < v_battle.join_amount then raise exception 'Insufficient balance.'; end if;
  if v_battle.currency = 'coins' then
    update public.rorisk_users set coins = coins - v_battle.join_amount where uuid = p_user_uuid returning * into v_user;
  else
    update public.rorisk_users set rocoins = rocoins - v_battle.join_amount where uuid = p_user_uuid returning * into v_user;
  end if;
  v_team := case when v_battle.mode in ('2v2', '2v2v2') then p_slot / 2 when v_battle.mode = '3v3' then p_slot / 3 else p_slot end;
  v_player := jsonb_build_object(
    'uuid', gen_random_uuid(), 'slot', p_slot, 'team', v_team, 'user_uuid', v_user.uuid,
    'roblox_id', v_user.roblox_id, 'username', v_user.username,
    'avatar_headshot', coalesce(v_user.avatar_headshot, '/default-avatar.png'),
    'rank', coalesce(v_user.rank, 'user'), 'level', coalesce(v_user.level, 0),
    'is_bot', false, 'wager_amount', v_battle.join_amount, 'outcome_total', 0,
    'payout_amount', 0, 'joined_at', now()
  );
  v_count := jsonb_array_length(v_battle.players) + 1;
  update public.rorisk_battles
  set players = players || jsonb_build_array(v_player),
      state = case when v_count >= player_count then 'countdown' else state end,
      started_at = case when v_count >= player_count then now() else started_at end,
      updated_at = now(), version = version + 1
  where uuid = p_battle_uuid returning * into v_battle;
  return jsonb_build_object('battle', to_jsonb(v_battle), 'user', to_jsonb(v_user), 'ready', v_count >= v_battle.player_count);
end;
$$;

create or replace function public.add_rorisk_battle_bot(
  p_battle_uuid uuid, p_creator_uuid uuid, p_slot integer, p_username text, p_avatar text
) returns jsonb language plpgsql security definer set search_path = public, extensions
as $$
declare
  v_battle public.rorisk_battles%rowtype;
  v_player jsonb;
  v_count integer;
  v_team integer;
begin
  select * into v_battle from public.rorisk_battles where uuid = p_battle_uuid for update;
  if not found then raise exception 'This battle could not be found.'; end if;
  if v_battle.creator_uuid <> p_creator_uuid then raise exception 'Only the battle creator can call a bot.'; end if;
  if v_battle.state <> 'created' then raise exception 'This battle can no longer be joined.'; end if;
  if p_slot < 0 or p_slot >= v_battle.player_count then raise exception 'That battle seat is invalid.'; end if;
  if exists (select 1 from jsonb_array_elements(v_battle.players) player where (player->>'slot')::integer = p_slot) then raise exception 'That battle seat is already occupied.'; end if;
  v_team := case when v_battle.mode in ('2v2', '2v2v2') then p_slot / 2 when v_battle.mode = '3v3' then p_slot / 3 else p_slot end;
  v_player := jsonb_build_object(
    'uuid', gen_random_uuid(), 'slot', p_slot, 'team', v_team, 'user_uuid', null,
    'roblox_id', null, 'username', left(coalesce(p_username, 'Risk Bot'), 64),
    'avatar_headshot', coalesce(nullif(p_avatar, ''), '/default-avatar.png'),
    'rank', 'bot', 'level', 0, 'is_bot', true, 'wager_amount', 0,
    'outcome_total', 0, 'payout_amount', 0, 'joined_at', now()
  );
  v_count := jsonb_array_length(v_battle.players) + 1;
  update public.rorisk_battles
  set players = players || jsonb_build_array(v_player),
      state = case when v_count >= player_count then 'countdown' else state end,
      started_at = case when v_count >= player_count then now() else started_at end,
      updated_at = now(), version = version + 1
  where uuid = p_battle_uuid returning * into v_battle;
  return jsonb_build_object('battle', to_jsonb(v_battle), 'ready', v_count >= v_battle.player_count);
end;
$$;

create or replace function public.finalize_rorisk_battle(
  p_battle_uuid uuid, p_results jsonb, p_payouts jsonb, p_winner_slots smallint[],
  p_eos_block_id text, p_eos_block_number bigint, p_server_seed text
) returns jsonb language plpgsql security definer set search_path = public, extensions
as $$
declare
  v_battle public.rorisk_battles%rowtype;
  v_payout jsonb;
  v_player jsonb;
  v_players jsonb;
  v_total bigint := 0;
begin
  select * into v_battle from public.rorisk_battles where uuid = p_battle_uuid for update;
  if not found then raise exception 'This battle could not be found.'; end if;
  if v_battle.state = 'completed' then return jsonb_build_object('battle', to_jsonb(v_battle)); end if;
  if v_battle.state not in ('countdown', 'pending', 'rolling', 'jackpot_spinning') then raise exception 'This battle is not ready to settle.'; end if;
  if encode(digest(p_server_seed, 'sha256'), 'hex') <> v_battle.server_seed_hash then raise exception 'The battle seed is invalid.'; end if;
  if jsonb_typeof(p_results) <> 'array' or jsonb_typeof(p_payouts) <> 'array' then raise exception 'The battle result is invalid.'; end if;
  for v_payout in select value from jsonb_array_elements(p_payouts) loop
    select value into v_player from jsonb_array_elements(v_battle.players) where (value->>'slot')::integer = (v_payout->>'slot')::integer;
    if v_player is not null and not coalesce((v_player->>'is_bot')::boolean, false)
      and nullif(v_player->>'user_uuid', '') is not null and greatest(0, (v_payout->>'amount')::bigint) > 0 then
      if v_battle.currency = 'coins' then
        update public.rorisk_users set coins = coins + greatest(0, (v_payout->>'amount')::bigint) where uuid = (v_player->>'user_uuid')::uuid;
      else
        update public.rorisk_users set rocoins = rocoins + greatest(0, (v_payout->>'amount')::bigint) where uuid = (v_player->>'user_uuid')::uuid;
      end if;
    end if;
    v_total := v_total + greatest(0, (v_payout->>'amount')::bigint);
  end loop;
  select coalesce(jsonb_agg(
    jsonb_set(
      jsonb_set(player, '{outcome_total}', to_jsonb(coalesce((select sum((result->>'itemAmount')::bigint) from jsonb_array_elements(p_results) result where (result->>'slot')::integer = (player->>'slot')::integer), 0))),
      '{payout_amount}', to_jsonb(coalesce((select (payout->>'amount')::bigint from jsonb_array_elements(p_payouts) payout where (payout->>'slot')::integer = (player->>'slot')::integer limit 1), 0))
    ) order by (player->>'slot')::integer
  ), '[]'::jsonb) into v_players from jsonb_array_elements(v_battle.players) player;
  update public.rorisk_battles
  set state = 'completed', current_round = total_rounds, players = v_players, results = p_results,
      winner_slots = coalesce(p_winner_slots, '{}'), payout_amount = v_total,
      eos_block_id = p_eos_block_id, eos_block_number = p_eos_block_number,
      completed_at = now(), updated_at = now(), version = version + 1
  where uuid = p_battle_uuid returning * into v_battle;
  return jsonb_build_object('battle', to_jsonb(v_battle));
end;
$$;

